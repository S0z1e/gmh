// Package failureguard bounds repeated failures within one turn. Its caller
// owns state capture and tool execution; the guard only admits attempts and
// records their outcomes. A zero Guard is ready to use, on one goroutine.
package failureguard

type Kind string

const (
	Unknown             Kind = "unknown"
	InvalidInput        Kind = "invalid_input"
	PolicyDenied        Kind = "policy_denied"
	Environment         Kind = "environment"
	Transient           Kind = "transient"
	VerificationFailure Kind = "verification_failure"
)

const (
	DenyAfter             = 3
	MaxStateProbesPerCall = 2
	MaxStateProbesPerTurn = 8
	maxRememberedVersions = 2 * (DenyAfter + MaxStateProbesPerCall)
)

// Decision describes admission of this attempt, not its execution result.
type Decision struct {
	Denied     bool
	Failures   int
	Kind       Kind
	StateProbe bool
}

type history struct {
	failures, probes int
	kind             Kind
	postRevision     string
	versions         map[string]struct{}
	sealed           bool
}

type Guard struct {
	calls  map[string]*history
	probes int
}

// Admit reserves permission for an attempt. A key is the canonical effective
// invocation. Revision is an opaque, proven relevant-state version; empty means
// unknown. A read succeeding or output text changing is not revision evidence.
//
// After DenyAfter failures, only environment, transient and verification failures
// can admit a changed-state probe. Both the last failure's post-execution version
// and the current version must be known. Each admitted probe consumes its slot
// immediately, even if approval later prevents execution. Do not use Admit as a
// read-only status query: asking twice cannot reserve the same probe twice.
func (g *Guard) Admit(key, revision string) Decision {
	h := g.entry(key)
	d := Decision{Failures: h.failures, Kind: h.kind}
	if h.failures < DenyAfter {
		h.remember(revision)
		return d
	}
	d.Denied = true
	if !canProbe(h.kind) || h.postRevision == "" || revision == "" || h.sealed || h.probes >= MaxStateProbesPerCall || g.probes >= MaxStateProbesPerTurn {
		return d
	}
	if _, seen := h.versions[revision]; seen {
		return d
	}
	h.remember(revision)
	if h.sealed {
		return d
	}
	h.probes++
	g.probes++
	d.Denied, d.StateProbe = false, true
	return d
}

// ObserveFailure records an executed failure or a classified rejection. Capture
// postRevision after the failed attempt: files generated by that failure must
// not themselves count as a repair before the next attempt. Unknown evidence
// replaces the previous version rather than silently reusing a stale version.
func (g *Guard) ObserveFailure(key string, kind Kind, postRevision string) int {
	h := g.entry(key)
	h.failures++
	h.kind, h.postRevision = normalizeKind(kind), postRevision
	h.remember(postRevision)
	return h.failures
}

func (g *Guard) entry(key string) *history {
	if g.calls == nil {
		g.calls = make(map[string]*history)
	}
	h := g.calls[key]
	if h == nil {
		h = &history{kind: Unknown, versions: make(map[string]struct{})}
		g.calls[key] = h
	}
	return h
}

// ObserveSuccess clears only this fingerprint's history, returning whether a
// known failure was resolved. Successful unrelated reads return false and do
// not reset other failures. Success never refunds the turn's probe allowance.
func (g *Guard) ObserveSuccess(key string) bool {
	h := g.calls[key]
	delete(g.calls, key)
	return h != nil && h.failures > 0
}

func (h *history) remember(revision string) {
	if revision == "" {
		return
	}
	if _, seen := h.versions[revision]; seen {
		return
	}
	if len(h.versions) >= maxRememberedVersions {
		// Never forget a failed version and accidentally admit a replay. More
		// observations can arrive from jobs already in flight before denial.
		h.sealed = true
		return
	}
	h.versions[revision] = struct{}{}
}

func normalizeKind(kind Kind) Kind {
	switch kind {
	case InvalidInput, PolicyDenied, Environment, Transient, VerificationFailure:
		return kind
	default:
		return Unknown
	}
}

func canProbe(kind Kind) bool {
	return kind == Environment || kind == Transient || kind == VerificationFailure
}
